ALTER TABLE users ADD COLUMN IF NOT EXISTS recovery_code_hash VARCHAR(255);

CREATE TABLE IF NOT EXISTS auth_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email_key CHAR(64) NOT NULL,
    ip_key CHAR(64) NOT NULL,
    succeeded BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_auth_attempt_email_created ON auth_attempts (email_key, created_at);
CREATE INDEX IF NOT EXISTS idx_auth_attempt_ip_created ON auth_attempts (ip_key, created_at);

CREATE TABLE IF NOT EXISTS auth_sessions (
    session_id VARCHAR(128) PRIMARY KEY,
    payload TEXT NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_auth_sessions_expires ON auth_sessions (expires_at);
