-- Add the data tables required by the agriSense farm journal.
-- This migration leaves users, weather_cache, and existing message data intact.

CREATE TABLE IF NOT EXISTS farm_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_email VARCHAR(254) NOT NULL REFERENCES users(email) ON DELETE CASCADE,
    client_id UUID NOT NULL,
    title VARCHAR(120) NOT NULL,
    record_scope VARCHAR(20) NOT NULL DEFAULT 'crops' CHECK (record_scope IN ('crops', 'animals')),
    category VARCHAR(60) NOT NULL,
    due_date DATE NOT NULL,
    repeat_days INTEGER NOT NULL DEFAULT 0 CHECK (repeat_days BETWEEN 0 AND 365),
    note TEXT NOT NULL DEFAULT '',
    completed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
    UNIQUE (farmer_email, client_id)
);
CREATE INDEX IF NOT EXISTS idx_farm_tasks_farmer_due ON farm_tasks (farmer_email, due_date);

CREATE TABLE IF NOT EXISTS farm_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_email VARCHAR(254) NOT NULL REFERENCES users(email) ON DELETE CASCADE,
    client_id UUID NOT NULL,
    record_type VARCHAR(20) NOT NULL CHECK (record_type IN ('expense', 'sale', 'harvest')),
    record_scope VARCHAR(20) NOT NULL DEFAULT 'crops' CHECK (record_scope IN ('crops', 'animals')),
    item VARCHAR(150) NOT NULL,
    amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (amount >= 0),
    quantity NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    unit VARCHAR(30) NOT NULL DEFAULT '',
    entry_date DATE NOT NULL,
    note TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
    UNIQUE (farmer_email, client_id)
);
CREATE INDEX IF NOT EXISTS idx_farm_records_farmer_date ON farm_records (farmer_email, entry_date);

CREATE TABLE IF NOT EXISTS field_cases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_email VARCHAR(254) NOT NULL REFERENCES users(email) ON DELETE CASCADE,
    client_id UUID NOT NULL,
    subject VARCHAR(150) NOT NULL,
    subject_type VARCHAR(20) NOT NULL DEFAULT 'crops' CHECK (subject_type IN ('crops', 'animals')),
    severity VARCHAR(20) NOT NULL CHECK (severity IN ('Watching', 'Moderate', 'Urgent')),
    symptoms TEXT NOT NULL,
    photo_data BYTEA,
    photo_mime VARCHAR(80),
    photo_name VARCHAR(200),
    entry_date DATE NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
    UNIQUE (farmer_email, client_id)
);
CREATE INDEX IF NOT EXISTS idx_field_cases_farmer_date ON field_cases (farmer_email, entry_date);

CREATE TABLE IF NOT EXISTS animal_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_email VARCHAR(254) NOT NULL REFERENCES users(email) ON DELETE CASCADE,
    client_id UUID NOT NULL,
    animal_group VARCHAR(150) NOT NULL,
    activity VARCHAR(60) NOT NULL,
    quantity NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    unit VARCHAR(30) NOT NULL DEFAULT '',
    entry_date DATE NOT NULL,
    note TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
    UNIQUE (farmer_email, client_id)
);
CREATE INDEX IF NOT EXISTS idx_animal_records_farmer_date ON animal_records (farmer_email, entry_date);

CREATE TABLE IF NOT EXISTS farm_inventory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_email VARCHAR(254) NOT NULL REFERENCES users(email) ON DELETE CASCADE,
    client_id UUID NOT NULL,
    input_name VARCHAR(150) NOT NULL,
    input_type VARCHAR(30) NOT NULL CHECK (input_type IN ('seed', 'fertilizer', 'chemical', 'feed', 'fuel', 'other')),
    quantity NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    unit VARCHAR(30) NOT NULL,
    minimum_quantity NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK (minimum_quantity >= 0),
    expiry_date DATE,
    note TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
    UNIQUE (farmer_email, client_id)
);
CREATE INDEX IF NOT EXISTS idx_farm_inventory_farmer_name ON farm_inventory (farmer_email, input_name);

CREATE TABLE IF NOT EXISTS farm_stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_email VARCHAR(254) NOT NULL REFERENCES users(email) ON DELETE CASCADE,
    client_id UUID NOT NULL,
    stock_client_id UUID NOT NULL,
    linked_entry_client_id UUID NOT NULL,
    quantity_delta NUMERIC(14,3) NOT NULL CHECK (quantity_delta <> 0),
    entry_date DATE NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
    UNIQUE (farmer_email, client_id)
);
CREATE INDEX IF NOT EXISTS idx_farm_stock_movements_item ON farm_stock_movements (farmer_email, stock_client_id, entry_date);

CREATE TABLE IF NOT EXISTS farm_journal_preferences (
    farmer_email VARCHAR(254) PRIMARY KEY REFERENCES users(email) ON DELETE CASCADE,
    settings JSONB NOT NULL DEFAULT '{"task":true,"finance":true,"yield":true,"case":true,"inventory":true,"animal":true}'::jsonb,
    updated_at TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS field_harvests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_email VARCHAR(254) NOT NULL REFERENCES users(email) ON DELETE CASCADE,
    client_id UUID NOT NULL,
    field_name VARCHAR(120) NOT NULL,
    crop VARCHAR(120) NOT NULL,
    harvest_date DATE NOT NULL,
    quantity NUMERIC(14,3) NOT NULL CHECK (quantity > 0),
    unit VARCHAR(30) NOT NULL,
    grade VARCHAR(60) NOT NULL DEFAULT '',
    sale_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (sale_amount >= 0),
    note TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
    UNIQUE (farmer_email, client_id)
);
CREATE INDEX IF NOT EXISTS idx_field_harvests_farmer_date ON field_harvests (farmer_email, harvest_date DESC);
CREATE INDEX IF NOT EXISTS idx_field_harvests_farmer_plot ON field_harvests (farmer_email, field_name, crop);
