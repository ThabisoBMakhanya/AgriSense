-- PostgreSQL equivalent of schema.sql for a Neon database named `agrisense`.
-- Run this in the Neon SQL Editor after creating/selecting that database.

CREATE TABLE IF NOT EXISTS users (
    email VARCHAR(254) PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    phone VARCHAR(30),
    password_hash VARCHAR(255) NOT NULL,
    recovery_code_hash VARCHAR(255),
    region VARCHAR(30),
    weather_location VARCHAR(100),
    farm_size NUMERIC(6,2),
    crop_type VARCHAR(60),
    soil_quality SMALLINT CHECK (soil_quality BETWEEN 0 AND 255),
    farmer_type VARCHAR(20) NOT NULL DEFAULT 'crop',
    growth_stage VARCHAR(20) NOT NULL DEFAULT 'vegetative',
    soil_type VARCHAR(20) NOT NULL DEFAULT 'loamy',
    sms_opt_in BOOLEAN NOT NULL DEFAULT FALSE,
    registered_at TIMESTAMP,
    last_login TIMESTAMP
);

CREATE TABLE IF NOT EXISTS weather_cache (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location VARCHAR(120) NOT NULL UNIQUE,
    temp_c NUMERIC(5,2) NOT NULL,
    humidity_pct SMALLINT NOT NULL CHECK (humidity_pct BETWEEN 0 AND 255),
    rain_probability NUMERIC(5,4) NOT NULL DEFAULT 0,
    wind_kmh NUMERIC(6,2) NOT NULL DEFAULT 0,
    cloud_pct SMALLINT NOT NULL CHECK (cloud_pct BETWEEN 0 AND 255),
    condition_text VARCHAR(120) NOT NULL,
    raw_json JSONB NOT NULL,
    fetched_at TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_weather_fetched_at ON weather_cache (fetched_at);

CREATE TABLE IF NOT EXISTS ml_models (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_name VARCHAR(120) NOT NULL,
    model_path VARCHAR(255) NOT NULL,
    accuracy_score NUMERIC(6,5),
    trained_at TIMESTAMP NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS ml_predictions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id VARCHAR(254) NOT NULL,
    weather_snapshot_json JSONB NOT NULL,
    input_features_json JSONB NOT NULL,
    predicted_class VARCHAR(60) NOT NULL,
    confidence NUMERIC(6,5) NOT NULL,
    recommendation_text TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_prediction_farmer_created ON ml_predictions (farmer_id, created_at);

CREATE TABLE IF NOT EXISTS training_data (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    temp_c NUMERIC(5,2) NOT NULL,
    humidity_pct SMALLINT NOT NULL CHECK (humidity_pct BETWEEN 0 AND 255),
    rain_probability NUMERIC(5,4) NOT NULL,
    wind_kmh NUMERIC(6,2) NOT NULL,
    cloud_pct SMALLINT NOT NULL CHECK (cloud_pct BETWEEN 0 AND 255),
    condition_encoded VARCHAR(20) NOT NULL,
    farmer_type_encoded VARCHAR(20) NOT NULL,
    growth_stage VARCHAR(20) NOT NULL,
    soil_type_encoded VARCHAR(20) NOT NULL,
    season_encoded VARCHAR(20) NOT NULL,
    label_class VARCHAR(60) NOT NULL,
    source VARCHAR(20) NOT NULL DEFAULT 'synthetic' CHECK (source IN ('synthetic', 'manual')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sms_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_email VARCHAR(254) NOT NULL,
    recipient VARCHAR(30) NOT NULL,
    message TEXT NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('submitted', 'failed')),
    provider VARCHAR(40) NOT NULL DEFAULT 'Lunyazi',
    provider_response_json JSONB,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_sms_farmer_status_created ON sms_logs (farmer_email, status, created_at);

CREATE TABLE IF NOT EXISTS auth_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email_key CHAR(64) NOT NULL,
    ip_key CHAR(64) NOT NULL,
    succeeded BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_auth_attempt_email_created ON auth_attempts (email_key, created_at);
CREATE INDEX IF NOT EXISTS idx_auth_attempt_ip_created ON auth_attempts (ip_key, created_at);

CREATE TABLE IF NOT EXISTS auth_sessions (
    session_id VARCHAR(128) PRIMARY KEY,
    payload TEXT NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_auth_sessions_expires ON auth_sessions (expires_at);
